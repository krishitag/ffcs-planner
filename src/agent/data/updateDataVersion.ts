// Writes the date src/data last changed (from Git) into dataVersion.ts, so the deployed
// site can show it without needing Git history. Run after every `git pull upstream`:
//
//   npx tsx src/agent/data/updateDataVersion.ts
//
// (Run from the project root, so the relative paths below work.)
import { execSync } from 'child_process';
import { writeFileSync } from 'fs';

const OUTPUT_FILE = 'src/agent/data/dataVersion.ts';

// The short date (YYYY-MM-DD) of the last commit that touched src/data.
// Throws if Git or its history isn't available.
export function gitDataDate(): string {
  return execSync('git log -1 --format=%cs -- src/data', { encoding: 'utf8' }).trim();
}

if (require.main === module) {
  const date = gitDataDate();
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) {
    throw new Error(`Expected a date from git, got "${date}"`);
  }
  writeFileSync(
    OUTPUT_FILE,
    `// Generated by updateDataVersion.ts. Don't edit by hand; rerun the script after \`git pull upstream\`.\n` +
      `export const DATA_VERSION = '${date}';\n`
  );
  console.log(`DATA_VERSION = ${date} (written to ${OUTPUT_FILE})`);
}
